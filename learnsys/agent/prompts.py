def mode_label(mode: str) -> str:
    return {
        "explain": "讲解",
        "guide": "引导",
        "quiz": "测验",
        "quick": "速答",
    }.get(mode, "讲解")


def build_system(mode: str = "explain", has_image: bool = False,
                 profile: str = "", *, memories: str = "", summary: str = "",
                 code_debug: bool = False, concise: bool = True,
                 personal_state: str = "") -> str:
    """拼系统提示词：基础口径 + 长度档 + 模式 + 篇幅示例 + 会话摘要 + 学习档案 + 个人状态 + 长期记忆。

    `concise` 现在表示「自适应标准档」（True）还是「深入档」（False），不是「短 vs 长」。
    `summary` 是更早对话的压缩；`personal_state` 由路由层生成、本轮自动带入；
    `memories` 放在最后：它是用户亲口强调的跨会话规矩，必须压过默认风格。
    """
    parts = [BASE_SYSTEM, CONCISE_ADDITION if concise else DEEP_ADDITION]
    if code_debug:
        parts.append(CODE_DEBUG_RULE)
    addition = MODE_ADDITIONS.get(mode, "")
    if addition:
        parts.append(addition.strip())
    # 示例只给讲解模式的标准档：deep 是用户主动选了深入，quiz/guide/quick 各有自己的格式。
    if mode == "explain" and concise:
        parts.append(STYLE_EXAMPLES)
    if summary.strip():
        parts.append("【本会话摘要（更早的对话已压缩；细节以最近几轮为准）】\n"
                     + summary.strip()[:1200])
    if profile.strip():
        parts.append("【学习档案（用户自己维护 / 确认过的）】\n" + profile.strip()[:2000])
    if personal_state.strip():
        parts.append("【个人状态（本轮自动带入，不用再调工具核对）】\n"
                     + clip_personal_state(personal_state))
    if memories.strip():
        parts.append(memories.strip())
    if has_image:
        parts.append("这一轮带有截图；截图内容会在用户消息里给出。")
    return "\n\n".join(parts)


def build_user_text(question: str, *, context: str = "", context_title: str = "",
                    image_text: str = "", image_used_vision: bool = False,
                    attachment_name: str = "", attachment_text: str = "") -> str:
    """把「问题 + 截图转述/OCR + 上下文 + 挂载文档」拼成一条用户消息。"""
    parts: list[str] = []
    if image_text.strip():
        parts.append(IMAGE_NOTE_VISION if image_used_vision else IMAGE_NOTE_OCR)
        parts.append("【截图内容】\n" + image_text.strip()[:8000])
    if attachment_text.strip():
        name = attachment_name or "文档"
        parts.append(f"【参考文档：{name}】\n{attachment_text.strip()[:6000]}")
    if context.strip():
        label = context_title.strip() or "刚录到的课堂转写片段（供参考，可能不完整）"
        parts.append(f"【{label}】\n" + context.strip()[:2000])
    parts.append("【问题】\n" + question.strip())
    return "\n\n".join(parts)
