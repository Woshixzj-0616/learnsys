"""画像视图：从 agent_memories 编译出一份人看的 Markdown。

派生视图，不是真源；手改会在下次编译时被覆盖。提示词不读这个文件。
"""
from __future__ import annotations

import datetime as dt
import hashlib
import pathlib

from learnsys import store

PROFILE_KINDS = ("identity", "goal", "constraint")
META_KEY = "profile_view_hash"
FOLDER = "记忆档案"
NAME = "画像.md"


def _path(data_root) -> pathlib.Path:
    return pathlib.Path(data_root) / FOLDER / NAME


def _rows(conn) -> list[dict]:
    items = store.list_memories(
        conn, limit=500, status="active", kinds=PROFILE_KINDS)
    items.sort(key=lambda item: (float(item.get("confidence") or 0),
                                 item.get("updated_at") or ""), reverse=True)
    return items


def _source_hash(items: list[dict]) -> str:
    raw = "|".join(f"{item['id']}:{item.get('content_key')}" for item in items)
    return hashlib.sha256(raw.encode("utf-8")).hexdigest()


def compile_profile(data_root) -> dict:
    data_root = pathlib.Path(data_root)
    path = _path(data_root)
    path.parent.mkdir(parents=True, exist_ok=True)
    conn = store.connect(data_root / "learning.db")
    try:
        items = _rows(conn)
        stamp = dt.datetime.now().strftime("%Y-%m-%dT%H:%M:%S")
        lines = [
            "<!-- AUTO-GENERATED by learnsys; "
            "source=agent_memories; DO NOT EDIT -->",
            f"<!-- generated_at={stamp} -->",
            "# 用户画像",
            "",
            "> 本文件由长期记忆自动编译，手改会在下次编译时被覆盖；",
            "> 要改内容请到「设置 → Agent 记忆」。",
            f"> 本次来源：active 记忆 {len(items)} 条"
            "（identity / goal / constraint）。",
            "",
        ]
        if not items:
            lines.append("（还没有身份、目标或约束类记忆。）")
        for item in items:
            evidence = str(item.get("evidence") or "")
            lines.append(
                f"- {item['content']}\n"
                f"  （来源：{evidence or '未记录'}；置信度："
                f"{float(item.get('confidence') or 0):.2f}；"
                f"更新：{(item.get('updated_at') or '')[:10]}）")
        path.write_text("\n".join(lines) + "\n", encoding="utf-8")
        store.set_meta(conn, META_KEY, _source_hash(items))
    finally:
        conn.close()
    return {"ok": True, "path": str(path), "facts": len(items)}


def read_profile(data_root) -> str:
    try:
        return _path(data_root).read_text(encoding="utf-8", errors="replace")
    except OSError:
        return ""


def profile_is_stale(conn, data_root) -> bool:
    saved = store.meta_value(conn, META_KEY)
    return str(saved or "") != _source_hash(_rows(conn))
